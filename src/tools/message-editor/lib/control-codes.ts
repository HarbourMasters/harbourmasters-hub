// FONT_CHAR_TEX_SIZE = (16 * 16) / 2 = 128 bytes per glyph
const FONT_CHAR_TEX_SIZE = 128;

export function kanjiOffsetFromShiftJIS(code: number): number {
  let col = (code & 0xFF) - 0x40;
  if (col >= 0x40) col--;

  if (code >= 0x8800) {
    return (col + 0x30A + 0xBC * ((code >> 8) - 0x88)) << 7;
  }

  const index = col + 0xBC * ((code >> 8) - 0x81);
  if (index < 0 || index >= KANJI_LOOKUP_TABLE.length) return 0;
  const entry = KANJI_LOOKUP_TABLE[index];
  if (entry === 0) return 0;
  return entry << 7;
}

// Get kanjiFontTbl index from Shift-JIS code
export function kanjiFontTblIndex(sjisCode: number): number {
  const offset = kanjiOffsetFromShiftJIS(sjisCode);
  return offset / FONT_CHAR_TEX_SIZE;
}

