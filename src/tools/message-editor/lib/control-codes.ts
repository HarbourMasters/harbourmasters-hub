// Convert a Shift-JIS 16-bit code to a display string
export function sjisToDisplay(code: number): string {
  if (SJIS_TO_UNICODE[code]) return SJIS_TO_UNICODE[code];
  return `\\u${code.toString(16).toUpperCase().padStart(4, '0')}`;
}

// Check if a 16-bit code is a Japanese control code
export function isJpnControlCode(code: number): boolean {
  return code in JPN_CTRL_NAMES;
}

// Detect if message data is Japanese (16-bit wide characters)
// Japanese messages have 16-bit character codes >= 0x8100
// NES messages use 0x80-0x9E for accented French/German characters, so
// we must NOT flag those as Japanese.
export function isJapaneseMessage(data: Uint8Array): boolean {
  const len = Math.min(data.length, 64);

  // Look for SJIS multi-byte sequences: a byte in 0x81-0x9F followed by
  // a second byte in 0x40-0xFC. NES extended chars (0x80-0x9E) are
  // single-byte, so 0x81 followed by < 0x40 (e.g. a control code or ASCII)
  // is NOT Japanese. Only flag as Japanese if we see proper 2-byte SJIS pairs.
  for (let i = 0; i < len - 1; i++) {
    const byte = data[i]!;
    const next = data[i + 1]!;
    // SJIS lead byte ranges
    if ((byte >= 0x81 && byte <= 0x9F) || (byte >= 0xE0 && byte <= 0xEF)) {
      // SJIS trail byte range is 0x40-0xFC (excluding 0x7F)
      if (next >= 0x40 && next <= 0xFC && next !== 0x7F) {
        return true;
      }
    }
  }
  return false;
}
