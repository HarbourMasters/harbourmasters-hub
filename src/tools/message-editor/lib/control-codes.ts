// Reverse mapping: Unicode → game byte
export const UNICODE_TO_CHAR: Record<string, number> = {};
for (const [byte, unicode] of Object.entries(CHAR_TO_UNICODE)) {
  if (!unicode.startsWith('[')) {
    UNICODE_TO_CHAR[unicode] = parseInt(byte);
  }
}

// Convert a game byte to display string
export function gameByteToChar(byte: number): string {
  if (byte >= 0x20 && byte < 0x7F) return String.fromCharCode(byte);
  if (CHAR_TO_UNICODE[byte]) return CHAR_TO_UNICODE[byte];
  return `\\x${byte.toString(16).toUpperCase().padStart(2, '0')}`;
}

