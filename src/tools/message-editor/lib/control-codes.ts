// Extra bytes after the control code byte (from message_data_fmt.h macro argument counts)
export function getExtraBytes(code: number): number {
  switch (code) {
    case CTRL.COLOR:
    case CTRL.ITEM_ICON:
    case CTRL.FADE:
    case CTRL.BOX_BREAK_DELAYED:
    case CTRL.HIGHSCORE:
    case CTRL.SHIFT:
    case CTRL.TEXT_SPEED:
      return 1;
    case CTRL.TEXTID:
    case CTRL.SFX:
    case CTRL.FADE2:
      return 2;
    case CTRL.BACKGROUND:
      return 3;
    default:
      return 0;
  }
}

